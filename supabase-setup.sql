CREATE TABLE IF NOT EXISTS admissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  name TEXT,
  house_name TEXT,
  father_name TEXT,
  job TEXT,
  mother_name TEXT,
  
  
  madrasa_info TEXT,
  samastha_reg TEXT,
  school_info TEXT,
  address TEXT,
  phone TEXT,
  pin TEXT,
  district TEXT,
  whatsapp TEXT,
  aadhar TEXT,
  id_marks TEXT,
  samastha_agree TEXT,
  photo_url TEXT
);

ALTER TABLE admissions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow public insert" ON admissions;
CREATE POLICY "Allow public insert" ON admissions FOR INSERT TO anon, authenticated WITH CHECK (true);

INSERT INTO storage.buckets (id, name, public)
VALUES ('student-photos', 'student-photos', true)
ON CONFLICT (id) DO NOTHING;

DROP POLICY IF EXISTS "Allow public upload" ON storage.objects;
CREATE POLICY "Allow public upload" ON storage.objects FOR INSERT TO anon, authenticated WITH CHECK (bucket_id = 'student-photos');
